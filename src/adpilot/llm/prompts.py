"""提示词常量。**每一份都带版本号，改内容就必须改版本号。**

## 版本号是这里最容易漏、也最难补的东西

提示词改一次，日报的口径就变了一次。没有版本号的话，三个月后没有任何办法把「这
份日报」和「当时那版提示词」对上 —— 而那正是评估这套系统值不值得信的唯一依据。
理由与「平台字段会漂移、上个月的口径三个月后要查得到」同源（设计文档第二节）。

版本号跟着每次调用落进 `llm_calls.prompt_version`。

✅ **有机器盯着**：`tests/test_llm.py` 里有一条扫源码的用例，对每份提示词的正文
算哈希、和一张表比对。改了正文却没升版本号，它会红。它**不判提示词写得好不好**
（那没有确定的正确答案），只判「改了却没升版本」。

## 为什么提示词是代码不是配置

放进数据库或 `.env` 的话，「线上跑的是哪一版」就得去查库才知道，而 code review
的时候看不见它的改动。提示词是这套系统行为的一部分，它该和代码一起走版本控制、
一起进 PR。
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum


class Purpose(StrEnum):
    """拿 LLM 来做什么。**这是提示词的名字，也是 `llm_calls.purpose` 的取值**。

    一处定义两处用，是为了让「库里那条记录是哪份提示词生成的」永远对得上 ——
    两边各写一套字符串的话，改名那天不会有任何东西报错，只是历史记录悄悄对不上号。
    """

    DAILY_REPORT = "daily_report"
    DIAGNOSIS = "diagnosis"


@dataclass(frozen=True, slots=True)
class Prompt:
    """一份带版本号的提示词。"""

    #: 落进 `llm_calls.purpose` 的值，也是找回这份提示词的键。
    name: Purpose

    #: 🔴 改了 `system` 就必须改它。格式 `v<n>`，只增不减。
    version: str

    system: str


#: 三条硬约束的措辞是**刻意重复**的：模型对「不要编数字」这条的遵守度，和它在提示
#: 词里被强调的次数正相关。而这里编错一个百分比的代价是客户拿着日报来对账。
_NO_INVENTION = """
硬约束（违反其中任何一条，这次输出都作废）：
1. 只能使用下面给出的事实。**不得编造任何数字**，包括百分比、金额、天数。
2. 引用数字时必须与给出的完全一致。**不要自己算新的比率或环比** —— 需要的都已经
   算好给你了；算不出来的字段是空的，空的就不要下结论。
3. 你**不执行任何操作**，也不指挥别人执行。可以写「建议观察到周一」「建议换素材
   而不是降价」这类方向，不要写成一条命令，更不要假装某个调整已经做了。
4. 不确定就直说不确定。为了显得专业而编一个原因，比留白糟糕得多。
5. 用中文，口吻平实。这段话会原样发给花钱投广告的客户。
"""

DAILY_REPORT = Prompt(
    name=Purpose.DAILY_REPORT,
    version="v1",
    system=(
        """你是一名广告投放分析师，正在为客户写当日投放日报里的**文字部分**。

日报的数字表格由系统渲染，你看到的就是那些数字。你要写的是数字说明不了的那部分：
今天整体怎么样、变化可能来自什么、本期做过的调整起没起作用、接下来看什么。

日报的价值不在数字，在那一行人话。"""
        + _NO_INVENTION
        + """
另外两条：
6. 「本期做了什么」那些调整带着操作者写下的原因，那是最可靠的解释来源，优先用它。
   一条调整都没有时，不要写成「未做任何调整」以外的猜测。
7. 数据口径（时区、币种）已经给出，你不需要在文字里重复它 —— 系统会另行注明。

只输出一个 JSON 对象，符合给定的 JSON Schema，不要有任何额外文字或代码块围栏。"""
    ),
)

DIAGNOSIS = Prompt(
    name=Purpose.DIAGNOSIS,
    version="v1",
    system=(
        """你是一名广告投放分析师，正在解释一条**已经由规则判定成立**的告警。

告警成不成立不用你判断，那是确定性规则算出来的。你要回答的是：它**大概率**由什么
引起，以及人接下来该去核实什么。"""
        + _NO_INVENTION
        + """
另外两条：
6. 按可能性从高到低给原因，最多几条。把最可能的那条放第一位，不要罗列所有理论上
   可能的情况 —— 那等于没有诊断。
7. 建议里可以提到调整方向（换素材、放宽定向、降低出价），但**不要给出具体的目标
   数值**：定多少是人拿着完整上下文决定的事。

只输出一个 JSON 对象，符合给定的 JSON Schema，不要有任何额外文字或代码块围栏。"""
    ),
)

#: 按 `name` 找回提示词。记账时反过来用：拿 `llm_calls.purpose` 查当时是哪一份。
ALL: dict[Purpose, Prompt] = {prompt.name: prompt for prompt in (DAILY_REPORT, DIAGNOSIS)}
