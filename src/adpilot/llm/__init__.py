"""LLM 适配器与提示词。**这一层的边界比它的功能重要。**

## 它够不着什么，以及为什么这是好事

分层契约（`pyproject.toml`）把 `llm` 压在 `models` / `schemas` / `services` / `db`
**之下**。于是下面这几件事在这个包里**根本写不出来**，不是「约定不要写」：

| 想写的 | 结果 |
|---|---|
| `select(...)` 查一下这个账户的历史 | 契约当场拦下（够不着 `db` / `models`） |
| 把生成的日报存进库 | 同上 —— 它写不了库 |
| 调 `services.balance.record(...)` 去改点什么 | 同上 |
| `import schemas.portal.PortalMetricDay` 当输入类型 | 同上 |

这就是[设计文档第五节](../../../docs/design/2026-08-19-mvp-design.md)「LLM 只解释
不决策、不碰钱」那两条硬边界的**机器形态**。它比提示词硬得多：提示词可以被绕过，
而且绕过时没有任何东西会报错。这一层唯一能做的事是「结构化输入进去、结构化输出
出来」；要拿那个输出改任何东西，只能由 `services/` 去做，而那一步是确定性代码。

代价是它得自己定义输入输出的契约（`contracts.py`），够不着 `schemas/`。这不是
重复劳动：**LLM 层的契约和对外 API 的契约本来就该分开演进**，中间那道翻译由
`services/` 显式地做，而不是「把 ORM 对象直接扔给模型」。

## 数字不由这一层产生

日报由两部分组成，来源必须分开：**数字**由代码从 `daily_metrics` 算，**人话**由
LLM 写。落地手段是 `contracts.py` 里的输出模型**只有文字字段** —— 模型填不进数字
字段，因为那些字段在它的契约里根本不存在。于是「模型把 CPA 编成另一个值」在结构
上不可能发生。

⚠️ **保证不了的那条也写在这里**：它仍然可能在散文里编一个百分比（「成本上升了
40%」而实际是 24%）。没有任何机器判定能可靠拦住这件事 —— 正则抽数字会被「四成」
「近一半」绕过去。那道防线是人：**日报必须经人工修订才能发布**，理由与做法见
[LLM 日报与诊断设计](../../../docs/design/2026-08-21-llm-reports.md)第三节。

## 里面有什么

* `base.py` —— 供应商协议与一次调用的原始产物。**不 import 任何内部模块**
* `contracts.py` —— 输入输出的 Pydantic 契约（输出侧没有数字字段）
* `prompts.py` —— 提示词常量，**每一份都带版本号**
* `structured.py` —— 「调用 → 解析 → 校验失败重试」，返回值里带着要记账的调用明细
* `openai_compat.py` —— 唯一的真实供应商（任何 OpenAI 兼容端点）
* `fake.py` —— 测试用的假供应商。**CI 里一次真实调用都不发**
"""
